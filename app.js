const form = document.getElementById("summary-form");
const urlInput = document.getElementById("article-url");
const summarizeBtn = document.getElementById("summarize-btn");
const loadingBox = document.getElementById("loading-box");
const loadingMessage = document.getElementById("loading-message");
const errorBox = document.getElementById("error-box");
const results = document.getElementById("results");
const summaryContent = document.getElementById("summary-content");
const sourceLink = document.getElementById("source-link");
const sourceDomain = document.getElementById("source-domain");
let latestSummary = "";
let latestTitle = "Article summary";
let latestUrl = "";

const loadingMessages = [
  "Opening the article and extracting its content…",
  "Finding the main ideas and important details…",
  "Turning the article into a clear summary…"
];

function escapeHtml(value) {
  return value.replace(/[&<>"']/g, ch => ({ "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;", "'":"&#39;" }[ch]));
}
function renderSummary(text) {
  // Render a small, safe Markdown subset; all raw text is escaped first.
  const lines = escapeHtml(text).split(/\r?\n/);
  let html = "", inList = false;
  const closeList = () => { if (inList) { html += "</ul>"; inList = false; } };
  for (const raw of lines) {
    const line = raw.trim();
    if (!line) { closeList(); continue; }
    if (/^#{1,3}\s/.test(line)) {
      closeList(); html += `<h3>${line.replace(/^#{1,3}\s/, "")}</h3>`; continue;
    }
    if (/^[-*•]\s/.test(line)) {
      if (!inList) { html += "<ul>"; inList = true; }
      html += `<li>${line.replace(/^[-*•]\s/, "").replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")}</li>`;
      continue;
    }
    closeList();
    html += `<p>${line.replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>")}</p>`;
  }
  closeList();
  return html;
}
form.addEventListener("submit", async event => {
  event.preventDefault();
  const url = urlInput.value.trim();
  if (!url) return;
  errorBox.hidden = true;
  results.hidden = true;
  loadingBox.hidden = false;
  summarizeBtn.disabled = true;
  summarizeBtn.style.opacity = ".7";
  summarizeBtn.querySelector(".button-text").textContent = "Working…";
  let messageIndex = 0;
  loadingMessage.textContent = loadingMessages[0];
  const messageTimer = setInterval(() => {
    messageIndex = (messageIndex + 1) % loadingMessages.length;
    loadingMessage.textContent = loadingMessages[messageIndex];
  }, 2600);
  try {
    const response = await fetch("/api/summarize", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        url,
        length: document.getElementById("summary-length").value,
        style: document.getElementById("summary-style").value
      })
    });
    const data = await response.json().catch(() => ({}));
    if (!response.ok) throw new Error(data.error || "Couldn't summarize this page. Try another public article URL.");
    latestSummary = data.summary || "";
    latestTitle = data.title || "Article summary";
    latestUrl = url;
    summaryContent.innerHTML = renderSummary(latestSummary);
    sourceLink.href = url;
    sourceLink.textContent = latestTitle.length > 90 ? latestTitle.slice(0, 87) + "…" : latestTitle;
    sourceDomain.textContent = new URL(url).hostname.replace(/^www\./, "");
    results.hidden = false;
    results.scrollIntoView({ behavior: "smooth", block: "start" });
  } catch (error) {
    errorBox.textContent = error.message || "Something went wrong. Please try again.";
    errorBox.hidden = false;
  } finally {
    clearInterval(messageTimer);
    loadingBox.hidden = true;
    summarizeBtn.disabled = false;
    summarizeBtn.style.opacity = "1";
    summarizeBtn.querySelector(".button-text").textContent = "Summarize";
  }
});

document.getElementById("download-txt").addEventListener("click", () => {
  const content = `${latestTitle}\nSource: ${latestUrl}\n\n${latestSummary}\n\nGenerated by Briefly AI Article Summarizer`;
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = "briefly-summary.txt";
  document.body.appendChild(a); a.click(); a.remove(); URL.revokeObjectURL(a.href);
});
document.getElementById("download-pdf").addEventListener("click", () => {
  if (!latestSummary) return;
  if (!window.jspdf || !window.jspdf.jsPDF) {
    window.print();
    return;
  }
  const { jsPDF } = window.jspdf;
  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  const margin = 18, pageWidth = pdf.internal.pageSize.getWidth(), pageHeight = pdf.internal.pageSize.getHeight();
  const maxWidth = pageWidth - margin * 2;
  let y = 22;
  pdf.setFont("helvetica", "bold"); pdf.setFontSize(19); pdf.setTextColor(42, 39, 94);
  pdf.text("Briefly", margin, y); y += 10;
  pdf.setFontSize(15); pdf.setTextColor(30, 38, 55);
  const titleLines = pdf.splitTextToSize(latestTitle, maxWidth);
  pdf.text(titleLines, margin, y); y += titleLines.length * 7 + 3;
  pdf.setFont("helvetica", "normal"); pdf.setFontSize(9); pdf.setTextColor(95, 104, 122);
  const sourceLines = pdf.splitTextToSize("Source: " + latestUrl, maxWidth);
  pdf.text(sourceLines, margin, y); y += sourceLines.length * 4.5 + 7;
  pdf.setDrawColor(225, 228, 239); pdf.line(margin, y - 2, pageWidth - margin, y - 2); y += 5;
  pdf.setFontSize(11); pdf.setTextColor(45, 53, 69);
  const lines = pdf.splitTextToSize(latestSummary.replace(/[#*]/g, ""), maxWidth);
  for (const line of lines) {
    if (y > pageHeight - margin) { pdf.addPage(); y = margin; }
    pdf.text(line, margin, y); y += 5.8;
  }
  y += 7;
  if (y > pageHeight - margin) { pdf.addPage(); y = margin; }
  pdf.setFontSize(8); pdf.setTextColor(135, 140, 153);
  pdf.text("Generated by Briefly AI Article Summarizer · Verify important details in the original source.", margin, y);
  pdf.save("briefly-summary.pdf");
});
